#!/usr/bin/env python3
"""Export the mascot sprites from the macOS app's Sprites.swift to packages/mascots/sprites.json, the
shared copy the Windows app draws from. Run after changing a sprite; CI checks the two agree.

Usage: scripts/brand/export_sprites.py [--check]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SWIFT = ROOT / "apps/macos/Sources/HaryXCore/Sprites.swift"
OUT = ROOT / "packages/mascots/sprites.json"


def section(text: str, start: str) -> str:
    i = text.index(start)
    j = text.index("\n    }\n", i)
    return text[i:j]


def main() -> int:
    text = SWIFT.read_text()
    species = re.findall(r"case (\w+(?:, \w+)*)$", section(text, "public enum Species"), re.M)[0].split(", ")
    hsb = dict(
        (name, [float(x) for x in vals.split(", ")])
        for name, vals in re.findall(r"case \.(\w+): \(([\d., ]+)\)", section(text, "public var baseHSB"))
    )
    body = {
        name: re.findall(r'"([.A-Z]{16})"', rows)
        for name, rows in re.findall(r"case \.(\w+): \[(.*?)\]", section(text, "public var body"), re.S)
    }
    legs = {}
    for name, a, b in re.findall(r"case \.(\w+): \(\[(.*?)\],\s*\[(.*?)\]\)", section(text, "public var legs"), re.S):
        legs[name] = [re.findall(r'"([.A-Z]{16})"', a), re.findall(r'"([.A-Z]{16})"', b)]
    accents = {"robot": [0.35, 0.95, 1.0], "chick": [1.0, 0.55, 0.15], "cat": [1.0, 0.62, 0.72], "bunny": [1.0, 0.62, 0.72]}
    out = {
        "_comment": "Generated by scripts/brand/export_sprites.py from apps/macos/Sources/HaryXCore/Sprites.swift. Do not edit.",
        "canvas": 18,
        "legend": {".": "clear", "B": "body", "D": "shade", "L": "light", "E": "eye", "W": "white", "P": "blush", "K": "dark", "A": "accent"},
        "colors": {"white": [1, 1, 1], "blush": [1.0, 0.55, 0.62], "dark": [0.12, 0.10, 0.12], "eye": [0.09, 0.07, 0.08]},
        "species": [
            {
                "id": s,
                "baseHSB": hsb[s],
                "accent": accents.get(s, [1, 1, 1]),
                "eyeIsAccent": s == "robot",
                "body": body[s],
                "legs": legs[s],
            }
            for s in species
        ],
    }
    for s in out["species"]:
        assert s["body"] and len(s["legs"]) == 2 and all(s["legs"]), f"incomplete sprite {s['id']}"
    rendered = json.dumps(out, indent=2) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text() != rendered:
            print(f"{OUT} is out of date; run scripts/brand/export_sprites.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(rendered)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
